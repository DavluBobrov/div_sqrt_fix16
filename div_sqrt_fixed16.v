//=============================================================================
// div_sqrt_fixed16
//-----------------------------------------------------------------------------
// Цифровое устройство: деление и извлечение квадратного корня для
// 16-разрядных операндов с фиксированной точкой.
//
// Формат данных: Q1.15 (1 бит знака + 15 дробных разрядов),
//                вес младшего разряда = 2^-15, диапазон [-1 ; +1).
//
//   Деление:            result = round( op1 / op2 )
//                       Частное по модулю >= 1 в Q1.15 не представимо ->
//                       насыщение на крайние значения формата.
//                       op2 = 0 (деление на ноль) -> тоже насыщение.
//
//   Квадратный корень:  result = sqrt(op2),  op2 >= 0
//                       sqrt(X*2^-15) = sqrt(X*2^15) * 2^-15, т.е.
//                       извлекается целочисленный корень из {op2, 15'b0}.
//                       op2 < 0 -> насыщение (корень отрицательного числа).
//
// Алгоритмы - целочисленные побитовые, 1 бит результата за такт:
//   деление        - метод восстановления остатка (restoring division);
//   квадрат. корень- метод "цифра за цифрой" с восстановлением.
// 17 итераций (16 бит + доп. бит guard для округления) + 1 такт округления.
// Конвейера нет; сигнал busy блокирует запуск новой операции.
//
// Интерфейс:
//   clk          - тактовый сигнал
//   reset        - асинхронный сброс (активный 1)
//   start        - строб запуска (в момент start=1 захватываются op1/op2/rmode;
//                  игнорируется, пока busy=1)
//   div          - признак команды: div=1 -> деление, div=0 -> квадратный корень
//                  (входы div/sqrt объединены в один сигнал, как разрешено ТЗ)
//   op1[15:0]    - входной операнд - делимое
//   op2[15:0]    - входной операнд - делитель / операнд для корня
//   rmode[1:0]   - режим округления:
//                    00 - усечение (trunc, к нулю)
//                    01 - округление половины вверх  (half up)
//                    10 - округление половины вниз   (half down, к нулю)
//                    11 - округление половины до чётного (banker's rounding)
//   result[15:0] - результат вычислений (хранится до завершения след. команды)
//   ready        - сигнал готовности результата (1 в такт завершения)
//   busy         - сигнал занятости вычислительного блока (1 во время счёта)
//=============================================================================

module div_sqrt_fixed16 (
    input  wire        clk,
    input  wire        reset,
    input  wire        start,
    input  wire        div,          // 1 = деление, 0 = квадратный корень
    input  wire [15:0] op1,          // делимое
    input  wire [15:0] op2,          // делитель / radicand
    input  wire [1:0]  rmode,        // режим округления
    output reg  [15:0] result,
    output reg         ready,
    output reg         busy
);

    localparam S_IDLE = 2'd0;
    localparam S_RUN  = 2'd1;
    localparam S_DONE = 2'd2;

    reg  [1:0]  state;
    reg  [4:0]  cnt;              // счётчик итераций (18 циклов)

    // ---------------- регистры деления -------------------------------------
    reg         d_neg;            // знак частного
    reg  [15:0] d_div;            // |делитель|
    reg  [17:0] d_rem;            // остаток, сдвинутый влево (в w-битах)
    reg  [31:0] d_quo;            // частное Q17 (бит 31 = целая часть) + хвост
    reg         d_ovf;            // переполнение / деление на ноль

    // ---------------- регистры квадратного корня ---------------------------
    reg  [16:0] s_res;            // накопленный корень (17 бит: + guard)
    reg  [18:0] s_rem;            // неотрицательный остаток (2 новых битa снизу)
    reg  [31:0] s_op;             // {radicand, 15'b0}
    reg         s_ovf;            // недопустимый операнд (op2 < 0)

    // -------- признаки округления (по модулю результата) -------------------
    reg         ovf;              // d_ovf/s_ovf, зафиксированный в DONE
    reg  [16:0] mag;              // усечённый модуль результата (17 бит)
    reg         guard;            // отброшенный старший дробный бит
    reg         sticky_any;       // наличие единиц ниже guard

    wire [15:0] MAXPOS = 16'h7FFF;   // наибольший положительный Q1.15
    wire [15:0] MAXNEG = 16'h8000;   // -1 (наибольшее по модулю отрицательное)

    // ------- компаратор/вычитатель деления: 2*rem ?>= |div| ----------------
    wire [16:0] rem_shifted = {d_rem[15:0], 1'b0};   // остаток < |div| <= 16'h8000
    wire [16:0] rem_sub     = rem_shifted - {1'b0, d_div};
    wire        sub_ok      = ~rem_sub[16];

    // ------- компаратор/вычитатель корня: rem - ((res<<1)|1) ---------------
    wire [18:0] s_trial = {2'b0, s_res, 1'b0} + 19'd1;     // (res<<1)|1
    wire [18:0] s_diff  = s_rem - s_trial;
    wire        s_ok    = ~s_diff[18];

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            state      <= S_IDLE;
            ready      <= 1'b0;
            busy       <= 1'b0;
            result     <= 16'b0;
            cnt        <= 5'd0;
            d_neg      <= 1'b0;
            d_div      <= 16'b0;
            d_rem      <= 17'b0;
            d_quo      <= 32'b0;
            d_ovf      <= 1'b0;
            s_res      <= 17'b0;
            s_rem      <= 19'b0;
            s_op       <= 32'b0;
            s_ovf      <= 1'b0;
            ovf        <= 1'b0;
            mag        <= 17'b0;
            guard      <= 1'b0;
            sticky_any <= 1'b0;
        end else begin
            case (state)
            //---------------------------------------------------------- IDLE
            S_IDLE: begin
                ready <= 1'b0;
                if (start && !busy) begin
                    busy  <= 1'b1;
                    state <= S_RUN;
                    cnt   <= 5'd0;
                    if (div) begin
                        // ==================== ДЕЛЕНИЕ =======================
                        d_neg <= op1[15] ^ op2[15];
                        d_div <= op2[15] ? (~op2 + 16'b1) : op2;
                        d_rem <= op1[15] ? (~op1 + 16'b1) : op1;
                        d_quo <= 32'b0;
                        // деление на ноль (включая -0 и 16'h8000 -> |div|=0)
                        d_ovf <= ~(op2[15] ? (op2 != 16'h8000) : (op2 != 16'b0));
                    end else begin
                        // ================ КВАДРАТНЫЙ КОРЕНЬ ================
                        s_ovf <= op2[15];                  // op2 < 0
                        s_res <= 17'b0;
                        s_rem <= 19'b0;
                        s_op  <= {op2, 15'b0};             // X * 2^15
                    end
                end
            end
            //----------------------------------------------------------- RUN
            S_RUN: begin
                if (div) begin
                    // ---- итерация деления (восстановление остатка) ---------
                    // старший бит rem_shifted = очередной бит частного
                    d_quo <= {d_quo[30:0], rem_shifted[16]};
                    d_rem <= sub_ok ? rem_sub : rem_shifted;
                    d_ovf <= d_ovf | (d_quo[31] & ~rem_shifted[16]); // целая часть >= 1
                end else begin
                    // ---- итерация квадратного корня (цифра за цифрой) ------
                    if (s_ok) begin
                        s_rem <= {s_diff[16:0], 2'b00} + {15'b0, s_op[31:30]};
                        s_res <= {s_res[15:0], 1'b1};
                    end else begin
                        s_rem <= {s_rem[16:0], 2'b00} + {15'b0, s_op[31:30]};
                        s_res <= {s_res[15:0], 1'b0};
                    end
                    s_op <= s_op << 2;
                end

                if (cnt == 5'd17) begin
                    // ------------- фиксация признаков для округления --------
                    ovf        <= div ? (d_ovf | d_quo[31]) : s_ovf;
                    mag        <= div ? d_quo[30:15] : s_res[16:1];
                    guard      <= div ? d_quo[14] : s_res[0];
                    sticky_any <= div ? (|d_quo[13:0]) : (|s_rem);
                    state      <= S_DONE;
                end else begin
                    cnt <= cnt + 5'd1;
                end
            end
            //---------------------------------------------------------- DONE
            S_DONE: begin : blk_round
                // коррекция "дополнения до двух": при отбрасывании разрядов
                // trunc соответствует округлению к нулю, если модуль увеличить
                // на 1 при наличии отброшенных единиц (guard|sticky).
                reg [16:0] mt;
                reg        inc;
                begin
                    mt  = mag;
                    inc = 1'b0;
                    if (!ovf && (guard | sticky_any)) begin   // есть отброшенные разряды
                        case (rmode)
                            2'b01:   inc = 1'b1;                 // half up
                            2'b10:   inc = sticky_any;           // half down
                            2'b11:   inc = sticky_any | ~mt[0];  // half even
                            default: inc = 1'b0;                 // trunc
                        endcase
                    end
                    if (!ovf && inc) mt = mt + 17'd1;            // носитель уходит в ovf
                end

                if (ovf || mt[16])
                    result <= (div && d_neg) ? MAXNEG : MAXPOS;  // насыщение
                else if (div && d_neg && mt[15:0] != 16'b0)
                    result <= ~mt[15:0];                         // -|x| (two's complement)
                else
                    result <= mt[15:0];

                ready <= 1'b1;
                busy  <= 1'b0;
                state <= S_IDLE;
            end
            default: state <= S_IDLE;
            endcase
        end
    end

endmodule
